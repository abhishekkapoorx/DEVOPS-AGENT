"""Generate Alertmanager installation artifacts for supported Kubernetes setups."""

from __future__ import annotations

from io import BytesIO
from zipfile import ZIP_DEFLATED, ZipFile


def _quote(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def kustomize_bundle(endpoint: str, token: str) -> bytes:
    """Return a Kustomize overlay for a plain Alertmanager Deployment."""
    files = {
        "kustomization.yaml": """apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - webhook-secret.yaml
  - alertmanager-config.yaml
patches:
  - path: alertmanager-patch.yaml
""",
        "webhook-secret.yaml": f"""apiVersion: v1
kind: Secret
metadata:
  name: incident-agent-webhook-token
  namespace: monitoring
type: Opaque
stringData:
  token: {_quote(token)}
""",
        "alertmanager-config.yaml": f"""apiVersion: v1
kind: ConfigMap
metadata:
  name: incident-agent-webhook-receiver
  namespace: monitoring
data:
  receiver.yaml: |
    route:
      receiver: incident-investigation-agent
      group_wait: 10s
      group_interval: 30s
      repeat_interval: 1h
    receivers:
      - name: incident-investigation-agent
        webhook_configs:
          - url: \"{_quote(endpoint)}\"
            send_resolved: true
            http_config:
              authorization:
                type: Bearer
                credentials_file: /etc/alertmanager/webhook-token/token
""",
        "alertmanager-patch.yaml": """apiVersion: apps/v1
kind: Deployment
metadata:
  name: alertmanager
  namespace: monitoring
spec:
  template:
    spec:
      volumes:
        - name: webhook-token
          secret:
            secretName: incident-agent-webhook-token
      containers:
        - name: alertmanager
          volumeMounts:
            - name: webhook-token
              mountPath: /etc/alertmanager/webhook-token
              readOnly: true
""",
        "README.md": """# Alertmanager webhook overlay

This overlay assumes a Deployment named `alertmanager` in the `monitoring`
namespace. Merge `receiver.yaml` into the active Alertmanager configuration
before applying the overlay, then reload Alertmanager.
""",
    }
    output = BytesIO()
    with ZipFile(output, "w", ZIP_DEFLATED) as archive:
        for name, content in files.items():
            archive.writestr(name, content)
    return output.getvalue()


def helm_values(endpoint: str, token: str) -> str:
    """Return values for a chart that supports Alertmanager secret mounting."""
    return f"""# Generated by DevOps Agent
alertmanager:
  config:
    route:
      receiver: incident-investigation-agent
      group_wait: 10s
      group_interval: 30s
      repeat_interval: 1h
    receivers:
      - name: incident-investigation-agent
        webhook_configs:
          - url: \"{_quote(endpoint)}\"
            send_resolved: true
            http_config:
              authorization:
                type: Bearer
                credentials_file: /etc/alertmanager/secrets/incident-agent-webhook-token/token
  extraSecretMounts:
    - name: incident-agent-webhook-token
      secretName: incident-agent-webhook-token
      mountPath: /etc/alertmanager/secrets/incident-agent-webhook-token
      readOnly: true
  secret:
    stringData:
      token: {_quote(token)}
"""


def operator_manifest(endpoint: str, token: str) -> str:
    """Return an AlertmanagerConfig and Secret for Prometheus Operator."""
    return f"""apiVersion: v1
kind: Secret
metadata:
  name: incident-agent-webhook-token
  namespace: monitoring
type: Opaque
stringData:
  token: {_quote(token)}
---
apiVersion: monitoring.coreos.com/v1alpha1
kind: AlertmanagerConfig
metadata:
  name: incident-investigation-agent
  namespace: monitoring
spec:
  route:
    receiver: incident-investigation-agent
    groupWait: 10s
    groupInterval: 30s
    repeatInterval: 1h
  receivers:
    - name: incident-investigation-agent
      webhookConfigs:
        - url: \"{_quote(endpoint)}\"
          sendResolved: true
          httpConfig:
            authorization:
              type: Bearer
              credentials:
                name: incident-agent-webhook-token
                key: token
"""


__all__ = ["helm_values", "kustomize_bundle", "operator_manifest"]
